#!/usr/bin/env node
/**
 * Generate the Arya market sources file from the single plugin manifest.
 *
 * The manifest is `AryaAI/scripts/release/arya-plugins.json`: it names every
 * Arya-authored plugin once, with the channel that decides how the package
 * reaches a user. This script projects the `market` channel into
 * `data/arya-sources.json`, which `publish-arya-batch.mjs` consumes, so the two
 * repositories never hand-maintain the same list twice.
 *
 * Descriptions are validated on the way through: a `zh` value carrying Latin-1
 * supplement characters is an encoding round-trip, not Chinese, and publishing
 * one bakes mojibake into the catalog every client downloads.
 *
 * Usage:
 *   node scripts/sync-arya-sources.mjs            rewrite data/arya-sources.json
 *   node scripts/sync-arya-sources.mjs --check    fail if it is out of date
 *
 * Override the manifest location with ARYA_PLUGINS_MANIFEST.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const SOURCES = join(ROOT, 'data', 'arya-sources.json')
const CATALOG = join(ROOT, 'data', 'arya-plugins.json')
const MANIFEST = process.env.ARYA_PLUGINS_MANIFEST
  ?? join(ROOT, '..', 'AryaAI', 'scripts', 'release', 'arya-plugins.json')
const checkOnly = process.argv.includes('--check')

const CHANNELS = new Set(['market', 'bundle'])
const REPO_RE = /^[\w.-]+\/[\w.-]+$/
const CJK_RE = /[\u4E00-\u9FFF]/
/** Latin-1 supplement runs are what UTF-8 read as Latin-1 looks like. */
const MOJIBAKE_RE = /[\u00C0-\u00FF]{2,}/

const failures = []

/** Read JSON, tolerating the UTF-8 BOM a Windows editor or shell may prepend. */
function readJson(path) {
  return JSON.parse(readFileSync(path, 'utf8').replace(/^\uFEFF/, ''))
}

const manifest = readJson(MANIFEST)
if (!Array.isArray(manifest.plugins) || manifest.plugins.length === 0) {
  throw new Error(`${MANIFEST}: no plugins`)
}

const seen = new Set()
const market = []
for (const plugin of manifest.plugins) {
  const where = plugin?.name ?? JSON.stringify(plugin)
  if (typeof plugin?.name !== 'string' || plugin.name === '') { failures.push(`${where}: missing name`); continue }
  if (seen.has(plugin.name)) failures.push(`${plugin.name}: duplicate entry`)
  seen.add(plugin.name)

  if (!CHANNELS.has(plugin.channel)) failures.push(`${plugin.name}: channel must be market or bundle`)
  if (typeof plugin.repo !== 'string' || !REPO_RE.test(plugin.repo)) failures.push(`${plugin.name}: invalid repo`)

  const hasWorkspace = typeof plugin.workspace === 'string'
  const hasClone = typeof plugin.clone === 'string'
  if (hasWorkspace === hasClone) failures.push(`${plugin.name}: needs exactly one of workspace or clone`)

  if (plugin.channel !== 'market') continue

  const description = plugin.description ?? {}
  if (typeof description.en !== 'string' || description.en.trim() === '') failures.push(`${plugin.name}: missing description.en`)
  if (typeof description.zh !== 'string' || description.zh.trim() === '') {
    failures.push(`${plugin.name}: missing description.zh`)
  } else {
    if (!CJK_RE.test(description.zh)) failures.push(`${plugin.name}: description.zh has no Chinese characters`)
    if (MOJIBAKE_RE.test(description.zh)) failures.push(`${plugin.name}: description.zh looks like mojibake (Latin-1 run)`)
  }
  if (typeof description.en === 'string' && MOJIBAKE_RE.test(description.en)) {
    failures.push(`${plugin.name}: description.en looks like mojibake (Latin-1 run)`)
  }

  market.push({ name: plugin.name, source: plugin.repo, description: { en: description.en, zh: description.zh } })
}

if (failures.length > 0) {
  for (const failure of failures) console.error(`sync-arya-sources: ${failure}`)
  console.error(`sync-arya-sources: ${failures.length} problem(s) in ${MANIFEST}`)
  process.exit(1)
}

const next = {
  comment: 'Generated by dsh-market scripts/sync-arya-sources.mjs from AryaAI scripts/release/arya-plugins.json '
    + '(channel "market"). Do not edit by hand: change the manifest and re-run the generator.',
  legacyNames: Array.isArray(manifest.legacyNames) ? manifest.legacyNames : [],
  plugins: market,
}
const text = `${JSON.stringify(next, null, 2)}\n`

// The published catalog must list exactly these packages; drift means an entry
// was retired, renamed, or published without being registered.
let catalogNames = new Set()
try {
  catalogNames = new Set(readJson(CATALOG).plugins.map(plugin => plugin.name))
} catch (error) {
  console.error(`sync-arya-sources: cannot read ${CATALOG}: ${error.message}`)
  process.exitCode = 1
}
const manifestNames = new Set(market.map(plugin => plugin.name))
const catalogOnly = [...catalogNames].filter(name => !manifestNames.has(name))
const manifestOnly = [...manifestNames].filter(name => !catalogNames.has(name))
if (catalogOnly.length > 0) console.error(`sync-arya-sources: in the catalog but not the manifest: ${catalogOnly.join(', ')}`)
if (manifestOnly.length > 0) console.error(`sync-arya-sources: in the manifest but not the catalog: ${manifestOnly.join(', ')}`)
if (catalogOnly.length > 0 || manifestOnly.length > 0) process.exitCode = 1

let current = ''
try { current = readFileSync(SOURCES, 'utf8') } catch { /* first run */ }

if (current === text) {
  console.log(`sync-arya-sources: up to date (${market.length} market plugins)`)
} else if (checkOnly) {
  console.error('sync-arya-sources: data/arya-sources.json is out of date; run node scripts/sync-arya-sources.mjs')
  process.exitCode = 1
} else {
  writeFileSync(SOURCES, text, 'utf8')
  console.log(`sync-arya-sources: wrote ${market.length} market plugins to data/arya-sources.json`)
}
